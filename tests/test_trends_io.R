source("scripts/lib/trends_io.R", encoding = "UTF-8")
test_dir <- tempfile("trends-io-")
dir.create(test_dir)
series_path <- file.path(test_dir, "series.csv")
writeLines(c("category: all", "", "month,interest", "2024-01,0", "2024-02,<1", "2024-03,15"), series_path)
df <- read_trends_series(series_path)
stopifnot(identical(df$value, c(0, 0, 15)), nrow(df) == 3L,
          identical(extract_search_vector(series_path, 5L), c(0, 0, 15, 0, 0)),
          identical(extract_search_vector(series_path, 2L), c(0, 0)))
dates <- parse_lifecycle_date(c("2024-02", "2024-02-29", "Jun-25", NA, "invalid"))
stopifnot(identical(as.character(dates), c("2024-02-01", "2024-02-29", "2025-06-01", NA, NA)))
bad_path <- file.path(test_dir, "bad.csv")
writeLines(c("month,interest", "2024-01,broken"), bad_path)
stopifnot(inherits(try(read_trends_series(bad_path), silent = TRUE), "try-error"))
writeLines(c("month,interest", "2024-02,10", "2024-01,20"), bad_path)
stopifnot(inherits(try(read_trends_series(bad_path), silent = TRUE), "try-error"))
# CP949 export with Korean metadata must fall back from UTF-8 cleanly.
korean_lines <- c("카테고리: 모든 카테고리", "월,검색량", "2024-01,20")
connection <- file(file.path(test_dir, "cp949.csv"), open = "wt", encoding = "CP949")
writeLines(korean_lines, connection)
close(connection)
stopifnot(identical(read_trends_series(file.path(test_dir, "cp949.csv"))$value, 20))
writeLines("temporary", file.path(test_dir, "~$ignored.csv"))
stopifnot(length(list_trends_files(test_dir)) == 3L)
cat("All Trends input checks passed.\n")
